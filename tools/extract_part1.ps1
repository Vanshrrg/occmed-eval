# Extracts the 48 assessment items (รพศ-รพท.) from the saved page into data/part1.js
# Usage (from the site folder):  powershell -ExecutionPolicy Bypass -File tools\extract_part1.ps1 "..\ระบบประเมินออนไลน์.html"
param([Parameter(Mandatory = $true)][string]$Source)

$h = [IO.File]::ReadAllText((Resolve-Path $Source), [Text.Encoding]::UTF8)
# Start at the criteria section of the page
$start = $h.IndexOf('เกณฑ์และแนวทางการตรวจประเมิน')
$end = $h.IndexOf('ตารางร้อยละการผ่านเกณฑ์')
$h = $h.Substring($start, $end - $start)

function Clean([string]$s) {
  $s = [regex]::Replace($s, '(?s)<(?!/?(p|br|ol|ul|li|strong|b|u)\b)[^>]*>', '')
  $s = [regex]::Replace($s, '<(/?)(p|br|ol|ul|li|strong|b|u)\b[^>]*>', '<$1$2>')
  $s = $s -replace '&nbsp;', ' '
  $s = [regex]::Replace($s, '<p>\s*</p>', '')
  $s = [regex]::Replace($s, '<(strong|u|b)>\s*</\1>', '')
  $s = [regex]::Replace($s, '[ \t]{2,}', ' ')
  $s = [regex]::Replace($s, '\s*\n\s*', "`n")
  $s = [regex]::Replace($s.Trim(), '^(</[a-z]+>\s*)+', '')
  $s = [regex]::Replace($s, '(\s*<[a-z]+>)+$', '')
  return $s.Trim()
}
function PlainText([string]$s) {
  $s = [regex]::Replace($s, '<[^>]+>', ' ') -replace '&nbsp;', ' '
  return ([regex]::Replace($s, '\s+', ' ')).Trim()
}

$markers = @()
foreach ($m in [regex]::Matches($h, '<h4 class="w3-padding w3-border-bottom w3-indigo w3-card">(.*?)</h4>')) {
  $markers += [pscustomobject]@{ pos = $m.Index; end = $m.Index + $m.Length; kind = 'comp'; text = (PlainText $m.Groups[1].Value) }
}
foreach ($m in [regex]::Matches($h, '<div class="w3-deep-purple[^"]*">(.*?)</div>')) {
  $markers += [pscustomobject]@{ pos = $m.Index; end = $m.Index + $m.Length; kind = 'sec'; text = (PlainText $m.Groups[1].Value) }
}
foreach ($m in [regex]::Matches($h, '<h3>(\d+)\s*(<span class="glyphicon glyphicon-star"></span>)?</h3>')) {
  $markers += [pscustomobject]@{ pos = $m.Index; end = $m.Index + $m.Length; kind = 'item'; no = [int]$m.Groups[1].Value; star = $m.Groups[2].Success }
}
foreach ($m in [regex]::Matches($h, 'รวมคะแนนตั้งแต่ข้อ')) {
  $markers += [pscustomobject]@{ pos = $m.Index; end = $m.Index; kind = 'stop' }
}
$markers = $markers | Sort-Object pos

$components = @(); $items = @(); $comp = 0; $sec = ''
for ($k = 0; $k -lt $markers.Count; $k++) {
  $mk = $markers[$k]
  if ($mk.kind -eq 'comp') {
    $comp++
    $components += [ordered]@{ no = $comp; title = ($mk.text -replace '^องค์ประกอบที่\s*\d+\s*', '') }
    $sec = ''
  } elseif ($mk.kind -eq 'sec') {
    $sec = $mk.text
  } elseif ($mk.kind -eq 'item') {
    $next = if ($k + 1 -lt $markers.Count) { $markers[$k + 1].pos } else { $h.Length }
    $body = $h.Substring($mk.end, $next - $mk.end)
    # Split into labelled blocks
    $blocks = @{}
    $labels = [regex]::Matches($body, '<strong><u>(.*?)</u></strong>')
    for ($j = 0; $j -lt $labels.Count; $j++) {
      $from = $labels[$j].Index + $labels[$j].Length
      $to = if ($j + 1 -lt $labels.Count) { $labels[$j + 1].Index } else { $body.Length }
      $blocks[(PlainText $labels[$j].Groups[1].Value)] = $body.Substring($from, $to - $from)
    }
    $critHtml = $blocks['เกณฑ์การให้คะแนน']
    $ol = [regex]::Match($critHtml, '(?s)<ol type="1" start="0">(.*?)</ol>')
    $criteria = @([regex]::Matches($ol.Groups[1].Value, '(?s)<li>(.*?)</li>') | ForEach-Object { PlainText $_.Groups[1].Value })
    $dup = @($items | Where-Object { $_.no -eq $mk.no }).Count
    $items += [ordered]@{
      id        = if ($dup -gt 0) { "$($mk.no)-$($dup + 1)" } else { "$($mk.no)" }
      no        = $mk.no
      component = $comp
      section   = $sec
      star      = [bool]$mk.star
      title     = Clean $blocks['องค์ประกอบของมาตรฐาน']
      guideline = Clean $blocks['แนวทางการพิจารณาตามเกณฑ์']
      evidence  = if ($blocks.ContainsKey('หลักฐานหรือเอกสารยืนยัน')) { Clean $blocks['หลักฐานหรือเอกสารยืนยัน'] } else { '' }
      criteria  = $criteria
    }
  }
}

# Items sharing a number are alternative variants (e.g. ข้อ 3 Clinic / Non Clinic)
foreach ($it in $items) {
  $same = @($items | Where-Object { $_.no -eq $it.no })
  if ($same.Count -gt 1) {
    $it.group = "$($it.no)"
    $it.variantLabel = ([regex]::Match((PlainText $it.title), '\(([^)]*)\)\s*$')).Groups[1].Value
    if (-not $it.variantLabel) { $it.variantLabel = "แบบที่ $([array]::IndexOf($same, $it) + 1)" }
  }
}

$out = [ordered]@{ components = $components; items = $items }
$json = $out | ConvertTo-Json -Depth 6
$dest = Join-Path $PSScriptRoot '..\data\part1.js'
New-Item -ItemType Directory -Force (Split-Path $dest) | Out-Null
[IO.File]::WriteAllText($dest, "// Generated by tools/extract_part1.ps1 - do not edit by hand`nwindow.PART1 = $json;`n", (New-Object Text.UTF8Encoding($false)))

"components: $($components.Count)"
$items | Group-Object { $_['component'] } | ForEach-Object { "comp $($_.Name): $($_.Count) entries, numbers $((($_.Group | ForEach-Object { $_.no }) | Sort-Object -Unique).Count)" }
$items | Where-Object { $_.criteria.Count -ne 4 } | ForEach-Object { "WARN item $($_.id) has $($_.criteria.Count) criteria" }
$items | Where-Object { $_.group } | ForEach-Object { "variant $($_.id): $($_.variantLabel)" }
